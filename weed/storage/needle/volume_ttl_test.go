// Package needle 实现了 SeaweedFS 的 Needle 存储格式
// 本文件包含 TTL (Time To Live) 功能的单元测试
package needle

import (
	"testing"
)

// =====================================================
// TTL (Time To Live) 测试说明
// =====================================================
// TTL 是 SeaweedFS 中用于自动过期删除文件的机制
// 当文件存储时间超过 TTL 设定值后，系统会自动清理该文件
//
// TTL 字符串格式：<数值><单位>
// 支持的时间单位：
//   - (无单位) / m: 分钟 (minute)
//   - h: 小时 (hour)
//   - d: 天 (day)
//   - w: 周 (week)
//   - M: 月 (month，按 30 天计算)
//   - y: 年 (year，按 365 天计算)
//
// 示例：
//   - "9"  或 "9m"  = 9 分钟
//   - "5h" = 5 小时 = 300 分钟
//   - "5d" = 5 天 = 7200 分钟
//   - "5w" = 5 周 = 50400 分钟
//   - "5M" = 5 月 = 216000 分钟
//   - "5y" = 5 年 = 2628000 分钟
//
// TTL 的存储格式：
//   - 内存/网络传输：使用 2 字节紧凑表示
//   - 包含：数值 (count) 和单位 (unit)
// =====================================================

// TestTTLReadWrite 测试 TTL 的解析、序列化和反序列化功能
// 验证以下功能：
//   1. ReadTTL: 从字符串解析 TTL
//   2. Minutes(): 将 TTL 转换为分钟数
//   3. ToBytes: 将 TTL 序列化为 2 字节
//   4. LoadTTLFromBytes: 从 2 字节反序列化 TTL
//   5. ToUint32/LoadTTLFromUint32: TTL 与 uint32 的相互转换
func TestTTLReadWrite(t *testing.T) {
	// ========================================
	// 测试 1：空字符串
	// ========================================
	// 空字符串表示无 TTL 限制（永不过期）
	// 返回的 TTL 分钟数应为 0
	ttl, _ := ReadTTL("")
	if ttl.Minutes() != 0 {
		t.Errorf("empty ttl:%v", ttl)
	}

	// ========================================
	// 测试 2：纯数字（默认单位为分钟）
	// ========================================
	// "9" 表示 9 分钟，与 "9m" 等价
	ttl, _ = ReadTTL("9")
	if ttl.Minutes() != 9 {
		t.Errorf("9 ttl:%v", ttl)
	}

	// ========================================
	// 测试 3：分钟单位 (m)
	// ========================================
	// "8m" 显式指定 8 分钟
	ttl, _ = ReadTTL("8m")
	if ttl.Minutes() != 8 {
		t.Errorf("8m ttl:%v", ttl)
	}

	// ========================================
	// 测试 4：小时单位 (h)
	// ========================================
	// "5h" = 5 小时 = 5 * 60 = 300 分钟
	ttl, _ = ReadTTL("5h")
	if ttl.Minutes() != 300 {
		t.Errorf("5h ttl:%v", ttl)
	}

	// ========================================
	// 测试 5：天单位 (d) - 短期
	// ========================================
	// "5d" = 5 天 = 5 * 24 * 60 = 7200 分钟
	ttl, _ = ReadTTL("5d")
	if ttl.Minutes() != 5*24*60 {
		t.Errorf("5d ttl:%v", ttl)
	}

	// ========================================
	// 测试 6：天单位 (d) - 中期
	// ========================================
	// "50d" = 50 天 = 50 * 24 * 60 = 72000 分钟
	ttl, _ = ReadTTL("50d")
	if ttl.Minutes() != 50*24*60 {
		t.Errorf("50d ttl:%v", ttl)
	}

	// ========================================
	// 测试 7：天单位 (d) - 1 年
	// ========================================
	// "365d" = 365 天 = 365 * 24 * 60 = 525600 分钟
	ttl, _ = ReadTTL("365d")
	if ttl.Minutes() != 365*24*60 {
		t.Errorf("365d ttl:%v", ttl)
	}

	// ========================================
	// 测试 8：天单位 (d) - 2 年
	// ========================================
	// "730d" = 730 天 = 730 * 24 * 60 = 1051200 分钟
	// 测试较大数值的处理能力
	ttl, _ = ReadTTL("730d")
	if ttl.Minutes() != 730*24*60 {
		t.Errorf("730d ttl:%v", ttl)
	}

	// ========================================
	// 测试 9：周单位 (w)
	// ========================================
	// "5w" = 5 周 = 5 * 7 * 24 * 60 = 50400 分钟
	ttl, _ = ReadTTL("5w")
	if ttl.Minutes() != 5*7*24*60 {
		t.Errorf("5w ttl:%v", ttl)
	}

	// ========================================
	// 测试 10：月单位 (M)
	// ========================================
	// "5M" = 5 月 = 5 * 30 * 24 * 60 = 216000 分钟
	// 注意：月按 30 天计算，这是一个近似值
	ttl, _ = ReadTTL("5M")
	if ttl.Minutes() != 5*30*24*60 {
		t.Errorf("5M ttl:%v", ttl)
	}

	// ========================================
	// 测试 11：年单位 (y)
	// ========================================
	// "5y" = 5 年 = 5 * 365 * 24 * 60 = 2628000 分钟
	// 注意：年按 365 天计算，不考虑闰年
	ttl, _ = ReadTTL("5y")
	if ttl.Minutes() != 5*365*24*60 {
		t.Errorf("5y ttl:%v", ttl)
	}

	// ========================================
	// 测试 12：序列化和反序列化 (字节数组)
	// ========================================
	// TTL 在存储和网络传输时使用 2 字节紧凑格式
	// 格式：[byte0][byte1] = [unit + count_high][count_low]
	//
	// 测试流程：
	// 1. 将 TTL 序列化为 2 字节数组
	// 2. 从字节数组反序列化为新的 TTL
	// 3. 验证分钟数一致
	output := make([]byte, 2)
	ttl.ToBytes(output)
	ttl2 := LoadTTLFromBytes(output)
	if ttl.Minutes() != ttl2.Minutes() {
		t.Errorf("ttl:%v ttl2:%v", ttl, ttl2)
	}

	// ========================================
	// 测试 13：序列化和反序列化 (uint32)
	// ========================================
	// TTL 也可以与 uint32 相互转换
	// 这在某些场景下更便于处理（如存储为数据库字段）
	//
	// 测试流程：
	// 1. 将 TTL 转换为 uint32
	// 2. 从 uint32 恢复 TTL
	// 3. 验证分钟数一致
	ttl3 := LoadTTLFromUint32(ttl.ToUint32())
	if ttl.Minutes() != ttl3.Minutes() {
		t.Errorf("ttl:%v ttl3:%v", ttl, ttl3)
	}

}
